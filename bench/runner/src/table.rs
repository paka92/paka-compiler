//! `paka-bench table <results-dir> <programs>` prints the published table (M6-32) in Markdown from
//! the raw results `run`, `costs` and `ui` in `<results-dir>`, `<programs>/list` and
//! `<programs>/loops`: each figure beside its GENESIS 3.2 expectation, with the word fixed by
//! docs/decisions/M6-02.md section 1.8, and each section 8 cost.

use super::read_list;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;
use std::path::Path;

/// What GENESIS 3.2 expects of a row, as M6-02 section 3 reads it.
#[derive(Clone, Copy, PartialEq, Debug)]
enum Expect {
    Parity,
    /// Behind, by no stated amount.
    Behind,
    /// Behind by 10 to 30%: pointer-heavy code.
    Pointer,
    NoneStated,
}

impl Expect {
    fn text(self) -> &'static str {
        match self {
            Expect::Parity => "parity",
            Expect::Behind => "behind, no amount",
            Expect::Pointer => "behind 10-30%",
            Expect::NoneStated => "none stated",
        }
    }

    /// The fixed word for a printed ratio (M6-02 section 1.8).
    fn word(self, ratio: f64) -> &'static str {
        match self {
            Expect::Behind | Expect::NoneStated => "measured",
            _ if ratio <= 1.10 => "parity",
            Expect::Pointer if ratio <= 1.30 => "as expected",
            _ => "worse than expected",
        }
    }
}

/// The lines of one raw results file.
struct Results(String);

impl Results {
    fn read(dir: &Path, name: &str) -> Result<Results, String> {
        let path = dir.join(name);
        fs::read_to_string(&path)
            .map(Results)
            .map_err(|e| format!("{}: {e}", path.display()))
    }

    /// The value of the `<name> <value>` fact line.
    fn fact(&self, name: &str) -> &str {
        let prefix = format!("{name} ");
        let value = self.0.lines().find_map(|l| l.strip_prefix(&prefix));
        value.unwrap_or("unknown")
    }

    /// The last attempt's median seconds of `what` under `<prefix> attempt <n> <what> median`.
    fn median(&self, prefix: &str, what: &str) -> Result<f64, String> {
        let head = format!("{prefix} attempt ");
        let found = self.0.lines().rev().find_map(|l| {
            match l.strip_prefix(&head)?.split(' ').collect::<Vec<_>>()[..] {
                [_, w, "median", m, ..] if w == what => m.parse().ok(),
                _ => None,
            }
        });
        found.ok_or_else(|| format!("no median of {what} under {prefix:?}"))
    }

    fn noisy(&self, prefix: &str) -> bool {
        self.0.lines().any(|l| l == format!("{prefix} noisy"))
    }

    /// The words of each line that starts with `prefix`, the prefix dropped.
    fn rows<'a>(&'a self, prefix: &'a str) -> impl Iterator<Item = Vec<&'a str>> {
        let lines = self.0.lines().filter_map(move |l| l.strip_prefix(prefix));
        lines.map(|l| l.split(' ').collect())
    }
}

/// A ratio as printed; the word is read from the printed figure.
fn ratio(a: f64, b: f64) -> f64 {
    format!("{:.2}", a / b).parse().unwrap_or(f64::NAN)
}

/// `<name> yes|no <function>...` lines: whether a trap branch is left in a loop of the kernel.
fn loops(programs: &Path) -> Result<BTreeMap<String, (bool, String)>, String> {
    let path = programs.join("loops");
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let lines = text
        .lines()
        .filter(|l| !l.is_empty() && !l.starts_with('#'));
    lines
        .map(|l| match l.split(' ').collect::<Vec<_>>()[..] {
            [name, answer @ ("yes" | "no"), ref functions @ ..] if !functions.is_empty() => {
                Ok((name.into(), (answer == "yes", functions.join(", "))))
            }
            _ => Err(format!(
                "{}: {l:?} is not `<name> yes|no <function>...`",
                path.display()
            )),
        })
        .collect()
}

pub fn print(dir: &Path, programs: &Path) -> Result<(), String> {
    let text = table(dir, programs)?;
    print!("{text}");
    Ok(())
}

fn table(dir: &Path, programs: &Path) -> Result<String, String> {
    let [run, costs, ui] = ["run", "costs", "ui"].map(|n| Results::read(dir, n));
    let (run, costs, ui) = (run?, costs?, ui?);
    let list = read_list(programs)?;
    let loops = loops(programs)?;
    let mut t = String::new();
    let w = &mut t;
    let shown = dir.display();
    let _ = writeln!(
        w,
        "# M6-32 · Release speed beside the paper's expectations\n"
    );
    let _ = writeln!(
        w,
        "Generated by `paka-bench table {shown} {}` from the raw results in {shown}: `run` from \
         `paka-bench run`, `costs` from `paka-bench costs`, `ui` from `paka-bench ui`. The method \
         is docs/decisions/M6-02.md. Do not edit by hand.\n",
        programs.display()
    );
    let _ = writeln!(
        w,
        "Machine: {}; kernel {}; governor {}; boost {}; pinned to logical CPU {}. Sources at \
         commit {}. libstdc++ {}.\n",
        run.fact("cpu"),
        run.fact("kernel"),
        run.fact("governor"),
        run.fact("boost"),
        run.fact("pinned-cpu"),
        run.fact("commit"),
        run.fact("libstdc++")
    );
    speed(w, &run, &list, &loops)?;
    section8(w, &run, &costs, &ui, &list, &loops)?;
    let _ = writeln!(w, "{NOT_CLAIMED}");
    Ok(t)
}

/// The version after `prefix` in `line`, up to the next space.
fn version<'a>(line: &'a str, prefix: &str) -> &'a str {
    let rest = line.split_once(prefix).map_or("unknown", |(_, r)| r);
    rest.split([' ', ')']).next().unwrap_or("unknown")
}

fn speed(
    w: &mut String,
    run: &Results,
    list: &[(String, String, bool)],
    loops: &BTreeMap<String, (bool, String)>,
) -> Result<(), String> {
    let clang = version(run.fact("compiler paka"), "clang version ");
    let rustc = run.fact("compiler rust");
    let _ = writeln!(w, "## Speed\n");
    let _ = writeln!(w, "| | paka | rust | c++ |\n|---|---|---|---|");
    let _ = writeln!(
        w,
        "| Compiler | clang {clang} | rustc {} | clang++ {} |",
        version(rustc, "rustc "),
        version(run.fact("compiler c++"), "clang version ")
    );
    let _ = writeln!(
        w,
        "| LLVM | {} | {} | {} |\n",
        clang.split('.').next().unwrap_or(clang),
        version(rustc, "(LLVM ")
            .split('.')
            .next()
            .unwrap_or("unknown"),
        clang.split('.').next().unwrap_or(clang)
    );
    let _ = writeln!(w, "{LLVM_NOTE}\n\n{CONTAINERS}\n");
    let _ = writeln!(
        w,
        "Each time is the median of 10 rounds, whole process, in seconds. The word is fixed by \
         M6-02 section 1.8 and read from the printed ratio: 'parity' at most 1.10; 'as expected' \
         on a pointer-heavy row up to 1.30; 'worse than expected' above the row's line; \
         'measured' where the paper names no amount. A noisy row, still above 5% spread after one \
         rerun, is marked so.\n"
    );
    let _ = writeln!(
        w,
        "| Program | Kind | Against | Paka s | Other s | Paka/other | Expected | Word |\n|---|---|---|---|---|---|---|---|"
    );
    for (name, kind, _) in list {
        let checked = list.iter().any(|p| p.0 == format!("{name}_wrap"));
        let trap_left = loops.get(name).is_none_or(|l| l.0);
        let (kind, against) = match kind.as_str() {
            "float" => {
                let cpp = if trap_left {
                    Expect::NoneStated
                } else {
                    Expect::Parity
                };
                ("float", vec![("rust", Expect::Parity), ("c++", cpp)])
            }
            "integer" if checked => (
                "integer, checked",
                vec![
                    ("rust-checked", Expect::NoneStated),
                    ("rust", Expect::Behind),
                    ("c++", Expect::Behind),
                ],
            ),
            "integer" => (
                "integer, wrapping",
                vec![("rust", Expect::Parity), ("c++", Expect::Parity)],
            ),
            _ => (
                "pointer",
                vec![("rust", Expect::Pointer), ("c++", Expect::Pointer)],
            ),
        };
        let paka = run.median(name, "paka")?;
        let noisy = if run.noisy(name) { " (noisy)" } else { "" };
        for (other, expect) in against {
            let them = run.median(name, other)?;
            let r = ratio(paka, them);
            let _ = writeln!(
                w,
                "| {name} | {kind} | {other} | {paka:.3} | {them:.3} | {r:.2} | {} | {}{noisy} |",
                expect.text(),
                expect.word(r)
            );
        }
    }
    let _ = writeln!(
        w,
        "\nFloat rows expect parity with C++ only where M6-19's check finds no trap branch left \
         in the kernel's loops (below, item 2); elsewhere 'none stated'.\n"
    );
    Ok(())
}

fn section8(
    w: &mut String,
    run: &Results,
    costs: &Results,
    ui: &Results,
    list: &[(String, String, bool)],
    loops: &BTreeMap<String, (bool, String)>,
) -> Result<(), String> {
    let _ = writeln!(w, "## Section 8 costs\n");
    let _ = writeln!(
        w,
        "GENESIS 3.2 states no amount for these; each row is 'measured'.\n\n\
         ### 1. Overflow checks\n\n\
         The checked kernel's time over its wrapping twin, both Paka release builds.\n\n\
         | Kernel | Checked s | Wrapping s | Checked/wrapping | Expected | Word |\n|---|---|---|---|---|---|"
    );
    for (name, ..) in list {
        let twin = format!("{name}_wrap");
        if list.iter().any(|p| p.0 == twin) {
            let (a, b) = (run.median(name, "paka")?, run.median(&twin, "paka")?);
            let noisy = mark(run.noisy(name) || run.noisy(&twin));
            let _ = writeln!(
                w,
                "| {name} | {a:.3} | {b:.3} | {:.2} | behind, amount to be measured | measured{noisy} |",
                ratio(a, b)
            );
        }
    }
    let _ = writeln!(
        w,
        "\n### 2. Bounds checks\n\n\
         The normal build's time over the measurement-only build without bounds checks \
         (`paka build --omit bounds`, M6-30), run only after the normal build printed the same \
         checksum.\n\n\
         | Kernel | Normal s | Without bounds checks s | Normal/without | Trap branch left in a loop | Word |\n|---|---|---|---|---|---|"
    );
    for (name, ..) in list {
        let prefix = format!("{name} bounds");
        if costs.0.contains(&format!("\n{prefix} attempt ")) {
            let a = costs.median(&prefix, "paka")?;
            let b = costs.median(&prefix, "paka-no-bounds")?;
            let left = yes_no(loops, name);
            let noisy = mark(costs.noisy(&prefix));
            let _ = writeln!(
                w,
                "| {name} | {a:.3} | {b:.3} | {:.2} | {left} | measured{noisy} |",
                ratio(a, b)
            );
        }
    }
    let _ = writeln!(
        w,
        "\nM6-19's check, per kernel: at `clang -O3`, as `paka build` makes the program, does a \
         block on a loop still branch to a bounds or overflow trap? The functions hold the hot \
         loops. Held by a test in paka/src/llvm.rs.\n\n\
         | Kernel | Functions | Trap branch left in a loop |\n|---|---|---|"
    );
    for (name, ..) in list {
        if let Some((_, functions)) = loops.get(name) {
            let _ = writeln!(w, "| {name} | {functions} | {} |", yes_no(loops, name));
        }
    }
    let _ = writeln!(w, "\n{STENCIL_NOTE}\n\n{NOT_BUILT}\n");
    let _ = writeln!(
        w,
        "### 4. Copying owned trees\n\n\
         A `measure` runtime times its copy routine through the whole run; the share is that \
         time over the same run. The normal build's time stands beside it, so the timing's own \
         cost shows.\n\n\
         | Program | Normal s | Measure build s | Copy routine s | Copy share of the run | Word |\n|---|---|---|---|---|---|"
    );
    for (name, ..) in list {
        let prefix = format!("{name} copies");
        if costs.0.contains(&format!("\n{prefix} attempt ")) {
            let normal = costs.median(&prefix, "paka")?;
            let whole = costs.median(&prefix, "paka-measure")?;
            let copy = costs.median(&prefix, "copy")?;
            let _ = writeln!(
                w,
                "| {name} | {normal:.3} | {whole:.3} | {copy:.3} | {:.1}% | measured{} |",
                copy / whole * 100.0,
                mark(costs.noisy(&prefix))
            );
        }
    }
    let _ = writeln!(
        w,
        "\n### 5. State copy per handler\n\n\
         A visual app with no window handles 10,000 clicks per handler on a state holding a \
         `List<Int>`; `Field` writes one small field, `Item` one list item. A `measure` runtime \
         times the copy itself.\n\n\
         | App | Handler | State copy per handler | Word |\n|---|---|---|---|"
    );
    for words in ui.rows("") {
        if let [app, handler, "state", "copy", ns, "ns", "per", "handler"] = words[..] {
            let _ = writeln!(w, "| {app} | {handler} | {ns} ns | measured |");
        }
    }
    let _ = writeln!(
        w,
        "\n### 6. Dev-mode slowdown\n\n\
         The to-do sample with no window plays bench/ui/todo/script (add 1,000 items, then tick \
         each) in dev and in release; a `measure` runtime times each frame. Paka code is update \
         and view; the whole frame adds layout. Drawing to a screen is not timed.\n"
    );
    for line in ui.0.lines() {
        if line.contains(" per frame: ") || line.contains(" dev/release: ") {
            let _ = writeln!(w, "- {line}");
        }
    }
    let _ = writeln!(
        w,
        "\nThe numeric kernels, once each in dev mode (`paka-diff --one dev`, compile included), \
         over the release median above. GENESIS 3.1 cites about 2-3x for unoptimized C and \
         WebAssembly and commonly 10-100x for Rust dev builds.\n\n\
         | Kernel | Dev s | Release s | Dev/release | Word |\n|---|---|---|---|---|"
    );
    for (name, kind, _) in list {
        if kind == "pointer" {
            continue;
        }
        let dev = costs
            .rows(&format!("{name} dev "))
            .find_map(|words| match words[..] {
                ["checksum", _, "time", t, "s"] => t.parse::<f64>().ok(),
                _ => None,
            });
        let dev = dev.ok_or_else(|| format!("no dev time for {name}"))?;
        let release = run.median(name, "paka")?;
        let _ = writeln!(
            w,
            "| {name} | {dev:.3} | {release:.3} | {:.1} | measured |",
            dev / release
        );
    }
    let _ = writeln!(w);
    Ok(())
}

fn yes_no(loops: &BTreeMap<String, (bool, String)>, name: &str) -> &'static str {
    match loops.get(name) {
        Some((true, _)) => "yes",
        Some((false, _)) => "no",
        None => "not checked",
    }
}

fn mark(noisy: bool) -> &'static str {
    if noisy { " (noisy)" } else { "" }
}

const LLVM_NOTE: &str = "Note: Rust is optimized by a newer LLVM. The C++ column, built by the \
same clang as Paka, is the same-optimizer comparison; a small gap to Rust may be the optimizer's.";

const CONTAINERS: &str = "Containers: Paka `List`, `Map<String, Int>` and self-containing enums; \
Rust `Vec`, `HashMap<&str, i64>` with its default hasher and `Option<Box<_>>` or `Box` tree nodes; \
C++ `std::vector` (`std::vector<char>` for sieve flags), `std::unordered_map<std::string_view, \
int64_t>` and `std::unique_ptr` tree nodes. 64-bit signed integers and 64-bit floats only; \
standard library only, one thread.";

const STENCIL_NOTE: &str = "stencil's `sweep` vectorizes with no check in its vector loop \
(M6-24); the check the table counts is in the scalar loop for the last items of a row.";

const NOT_BUILT: &str = "### 3. Reference counting and handle checks\n\n\
| Cost | Figure | Reason |\n|---|---|---|\n\
| Reference counting | not built | M2-10: the language has no shared type |\n\
| Handle checks | not built | M2-10: the language has no pools |\n\n\
The copy cost of owned trees stands in their place (item 4).";

const NOT_CLAIMED: &str = "## What the table does not claim\n\n\
- Single-threaded code on one machine at the baseline x86-64 level; nothing about vector code, \
threads or memory use.\n\
- The pointer-heavy rows are measured without pools, so they do not test the cause the paper \
gives for that gap, handle checks.";

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Scratch;

    #[test]
    fn each_word_follows_the_fixed_lines() {
        assert_eq!(Expect::Parity.word(1.10), "parity");
        assert_eq!(Expect::Parity.word(0.80), "parity");
        assert_eq!(Expect::Parity.word(1.11), "worse than expected");
        assert_eq!(Expect::Pointer.word(1.04), "parity");
        assert_eq!(Expect::Pointer.word(1.30), "as expected");
        assert_eq!(Expect::Pointer.word(1.31), "worse than expected");
        assert_eq!(Expect::Behind.word(3.0), "measured");
        assert_eq!(Expect::NoneStated.word(1.0), "measured");
        assert_eq!(ratio(1.1049, 1.0), 1.10);
        assert_eq!(ratio(1.1051, 1.0), 1.11);
    }

    /// Two programs through every section: the rows, ratios and words come out as M6-02 says.
    #[test]
    fn a_small_result_set_gives_its_rows() {
        let dir = Scratch::new().unwrap();
        let programs = dir.0.join("programs");
        fs::create_dir(&programs).unwrap();
        let list = "stencil float\nsieve integer\nsieve_wrap integer\nbfs pointer\n";
        fs::write(programs.join("list"), list).unwrap();
        let loops = "# c\nstencil yes sweep\nsieve yes count_primes\nsieve_wrap no count_primes\n";
        fs::write(programs.join("loops"), loops).unwrap();
        let run = "cpu Test CPU\ncompiler paka Ubuntu clang version 21.1.8 (1)\n\
            compiler rust rustc 1.96.1 (31fca3adb 2026-06-26) (LLVM 22.1.2)\n\
            compiler c++ Ubuntu clang version 21.1.8 (1)\n\
            stencil attempt 1 paka median 9.0 s\n\
            stencil attempt 2 paka median 1.0 s\nstencil attempt 2 rust median 1.0 s\n\
            stencil attempt 2 c++ median 0.8 s\nstencil noisy\n\
            sieve attempt 1 paka median 2.0 s\nsieve attempt 1 rust-checked median 1.0 s\n\
            sieve attempt 1 rust median 1.0 s\nsieve attempt 1 c++ median 1.0 s\n\
            sieve_wrap attempt 1 paka median 1.6 s\nsieve_wrap attempt 1 rust median 1.5 s\n\
            sieve_wrap attempt 1 c++ median 1.4 s\n\
            bfs attempt 1 paka median 1.2 s\nbfs attempt 1 rust median 1.0 s\n\
            bfs attempt 1 c++ median 0.9 s\n";
        let costs = "x\nsieve bounds attempt 1 paka median 2.0 s\n\
            sieve bounds attempt 1 paka-no-bounds median 1.6 s\n\
            bfs copies attempt 1 paka median 1.0 s\nbfs copies attempt 1 paka-measure median 1.1 s\n\
            bfs copies attempt 1 copy median 0.11 s\n\
            stencil dev checksum 1 time 20.0 s\nsieve dev checksum 1 time 40.0 s\n\
            sieve_wrap dev checksum 1 time 16.0 s\n";
        let ui = "copy_1000 Field state copy 1.5 ns per handler\n\
            todo dev/release: paka code 3.00, whole frame 1.50\n";
        for (name, text) in [("run", run), ("costs", costs), ("ui", ui)] {
            fs::write(dir.0.join(name), text).unwrap();
        }
        let got = table(&dir.0, &programs).unwrap();
        for row in [
            "| clang 21.1.8 | rustc 1.96.1 | clang++ 21.1.8 |",
            "| LLVM | 21 | 22 | 21 |",
            "| stencil | float | rust | 1.000 | 1.000 | 1.00 | parity | parity (noisy) |",
            "| stencil | float | c++ | 1.000 | 0.800 | 1.25 | none stated | measured (noisy) |",
            "| sieve | integer, checked | rust-checked | 2.000 | 1.000 | 2.00 | none stated | measured |",
            "| sieve | integer, checked | c++ | 2.000 | 1.000 | 2.00 | behind, no amount | measured |",
            "| sieve_wrap | integer, wrapping | c++ | 1.600 | 1.400 | 1.14 | parity | worse than expected |",
            "| bfs | pointer | rust | 1.200 | 1.000 | 1.20 | behind 10-30% | as expected |",
            "| bfs | pointer | c++ | 1.200 | 0.900 | 1.33 | behind 10-30% | worse than expected |",
            "| sieve | 2.000 | 1.600 | 1.25 | behind, amount to be measured | measured |",
            "| sieve | 2.000 | 1.600 | 1.25 | yes | measured |",
            "| sieve_wrap | count_primes | no |",
            "| bfs | 1.000 | 1.100 | 0.110 | 10.0% | measured |",
            "| copy_1000 | Field | 1.5 ns | measured |",
            "- todo dev/release: paka code 3.00, whole frame 1.50",
            "| stencil | 20.000 | 1.000 | 20.0 | measured |",
            "| sieve_wrap | 16.000 | 1.600 | 10.0 | measured |",
            "| Reference counting | not built | M2-10: the language has no shared type |",
        ] {
            assert!(got.contains(row), "{row}\n{got}");
        }
        fs::write(dir.0.join("costs"), "x\n").unwrap();
        let e = table(&dir.0, &programs).unwrap_err();
        assert_eq!(e, "no dev time for stencil");
    }
}
